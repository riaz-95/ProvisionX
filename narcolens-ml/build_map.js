// Builds narcolens-prototype/js/map_uae.js from Natural Earth 1:10m country outlines (world-atlas).
// Usage: node build_map.js <node_modules dir with world-atlas + topojson-client> <out.js>
const path = require('path'); const fs = require('fs');
const NM = process.argv[2];
const topo = require(path.join(NM, 'world-atlas/countries-10m.json'));
const { feature } = require(path.join(NM, 'topojson-client'));
const W = 600, H = 340, LAT0 = 22.5, LAT1 = 26.45, KX = Math.cos(24.5 * Math.PI / 180);
const S = H / (LAT1 - LAT0);                  // px per degree latitude
const LONC = 54.2, LON0 = LONC - (W / S / KX) / 2;
const proj = (lon, lat) => [(lon - LON0) * KX * S, (LAT1 - lat) * S];

function toPath(geom) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let d = '';
  for (const poly of polys) for (const ring of poly) {
    let last = null, n = 0, seg = '';
    for (const [lon, lat] of ring) {
      const p = proj(lon, lat);
      if (last && Math.hypot(p[0] - last[0], p[1] - last[1]) < 0.35) continue;
      seg += (n ? 'L' : 'M') + p[0].toFixed(1) + ',' + p[1].toFixed(1); last = p; n++;
    }
    if (n > 2) d += seg + 'Z';
  }
  return d;
}
const all = feature(topo, topo.objects.countries).features;
const by = (name) => all.find(f => f.properties.name === name);
const uae = by('United Arab Emirates');
const neighbours = ['Oman', 'Saudi Arabia', 'Qatar', 'Iran'].map(by).filter(Boolean);
const out = '/* UAE and neighbour outlines from Natural Earth 1:10m (public domain), generated by narcolens-ml/build_map.js */\n' +
  'window.NL = window.NL || {};\nNL.MAP = ' + JSON.stringify({
    w: W, h: H, lat1: LAT1, lon0: LON0, s: S, kx: KX,
    uae: toPath(uae.geometry),
    neighbours: neighbours.map(f => ({ name: f.properties.name, d: toPath(f.geometry) }))
  }) + ';\n' +
  'NL.MAP.project = function (lon, lat) { var m = NL.MAP; return [(lon - m.lon0) * m.kx * m.s, (m.lat1 - lat) * m.s]; };\n';
fs.writeFileSync(process.argv[3], out);
console.log('written', process.argv[3], Math.round(out.length / 1024) + ' KB', 'neighbours:', neighbours.map(f => f.properties.name).join(', '));
